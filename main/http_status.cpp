// GET /history?row=<trend id>[&source=x10a|modbus|env3] — one 24-hour series, oldest first.
// X10A is the backwards-compatible default; the external circulation witness identifies itself as
// MQTT, Modbus carries paired HomeHub measurements/state timelines, and ENV III owns three
// independent outdoor-climate rings.
//
//   {"id":"outdoor_air","source":"x10a","label":"R1T-Outdoor air temp.","dt":300,
//    "unit":"°C","t0":1784926349,"b0":5931421,"v":[131,null,…],
//    "held":[[0,42],[55,180]]}
//
// `v` holds tenths of the unit (the resolution the converters produce, so a sample is exact rather
// than rounded on the way in) or null. `held` run-length-marks WHICH of those nulls were the
// outdoor unit resting rather than a failure to measure — a plain number-or-null array stays
// readable by any consumer, and the reason for the nulls rides alongside instead of inside it
// (logic/history.hpp).
//
// `t0` is the wall-clock instant of sample 0, derived HERE from the newest committed sample's
// monotonic age — the ring itself advances on the monotonic clock, so it survives SNTP setting the
// time mid-boot. Omitted entirely when the clock has never synced: the UI then reads out an AGE,
// which is the same refusal-to-fabricate logic/timestamp.hpp already makes for syslog timestamps.
// `b0` is sample zero's monotonic bucket and aligns every source exactly even without wall time.
//
// Sent in CHUNKS. The body is ~1.5 KB — smaller than the model-dependent /values body — but it is a
// new allocation on a heap where the largest contiguous block is the binding limit, and chunking
// costs nothing here.
[[gnu::noinline]] static esp_err_t send_status_json_err(httpd_req_t* req, const char* status,
                                                        const char* body) {
    httpd_resp_set_status(req, status);
    return http_send_json(req, body);
}

[[gnu::noinline]] static void copy_bounded_str(char* dst, size_t max, const char* src) noexcept {
    if (!dst || !max) return;
    if (!src) {
        dst[0] = '\0';
        return;
    }
    std::strncpy(dst, src, max - 1);
    dst[max - 1] = '\0';
}

static esp_err_t h_history(httpd_req_t* req) {
    // Snapshot/header preparation allocates before transfer. Keep it outside OTA TLS;
    // the finished header and numeric samples then use the shared bounded stream boundary.
    if (ota_download_active()) return network_tls_busy(req);
    char q[96]  = {0};
    char id[32] = {0};
    if (httpd_req_get_url_query_str(req, q, sizeof(q)) != ESP_OK ||
        httpd_query_key_value(q, "row", id, sizeof(id)) != ESP_OK) {
        return send_status_json_err(req, "400 Bad Request",
                                    "{\"ok\":false,\"error\":\"row required\"}");
    }
    char            source[12]  = {0};
    const esp_err_t source_err  = httpd_query_key_value(q, "source", source, sizeof(source));
    const bool      has_source  = source_err == ESP_OK;
    const bool      modbus      = has_source && std::strcmp(source, "modbus") == 0;
    const bool      env3_source = has_source && std::strcmp(source, "env3") == 0;
    if (source_err != ESP_ERR_NOT_FOUND && !modbus && !env3_source &&
        (!has_source || std::strcmp(source, "x10a") != 0)) {
        return send_status_json_err(req, "400 Bad Request",
                                    "{\"ok\":false,\"error\":\"unknown source\"}");
    }
    const logic::TrendDef* def_ = logic::trend_by_id(id);
    // An unknown id is a 404, never a defaulted trend: answering with SOME series would look like a
    // working request and quietly attach the wrong sensor's history to whatever asked.
    size_t t = 0;
    if (def_) {
        while (t < logic::TREND_COUNT && &logic::TRENDS[t] != def_) t++;
    }
    const int  mb_t            = modbus ? logic::homehub_history_index(id) : -1;
    const bool native_modbus   = modbus && mb_active_profile() == ModbusProfile::Altherma4;
    const uint16_t mb_offset = modbus && mb_t >= 0 ? logic::HOMEHUB_HISTORIES[mb_t].offset : 0;
    const def::HomeHubReg* mb_reg =
        modbus && mb_t >= 0
            ? (native_modbus ? def::altherma4_find(mb_offset) : def::homehub_find(mb_offset))
            : nullptr;
    const int  env_t           = env3_source ? env3_history_index(id) : -1;
    bool       env3_configured = false;
    char       lbl[80] = {0}, unit[8] = {0};
    {
        const Config active_config = config();
        env3_configured = active_config.env3_enabled && env3_board_supported(active_config);
    } // Release the configuration snapshot before constructing the streamed history response.
    const bool x10a_unknown = !modbus && !env3_source && (!def_ || t >= logic::TREND_COUNT);
    const bool missing_modbus_profile =
        modbus && mb_t >= 0 && (!mb_reg || !def::homehub_has_quiet_activity(*mb_reg));
    if (x10a_unknown || (modbus && (mb_t < 0 || missing_modbus_profile)) ||
        (env3_source && (!env3_configured || env_t < 0))) {
        return send_status_json_err(req, "404 Not Found",
                                    "{\"ok\":false,\"error\":\"unknown trend\"}");
    }

    // Shared httpd-task-only scratch rather than stack: this handler runs on the httpd task, whose
    // stack overflowed in v1.0.12, and 576 + 580 bytes of locals is not worth the risk. Safe
    // because esp_http_server dispatches requests one at a time on that single task.
    auto(&samples)[logic::HISTORY_SAMPLES]             = s_httpd_route_scratch.history.samples;
    auto(&runs)[logic::HISTORY_MAX_RUNS][2]            = s_httpd_route_scratch.history.runs;
    uint32_t                    history_snapshot_epoch = 0;
    // The newest-sample age and sample zero's bucket come back from the SAME critical section as
    // the samples (HIST-01/e). Asked for afterwards, each took the lock again, and a bucket commit
    // between the copy and the question shifted sample zero by one bucket under the old t0/b0.
    // Static for the reason above; every snapshot call resets it before it can fill it.
    static logic::HistoryMeta history_meta;
    size_t                    n = 0;
    if (modbus)
        n = history_modbus_snapshot(static_cast<size_t>(mb_t), samples, logic::HISTORY_SAMPLES,
                                    &history_snapshot_epoch, &history_meta);
    else if (env3_source)
        n = history_env3_snapshot(static_cast<size_t>(env_t), samples, logic::HISTORY_SAMPLES,
                                  &history_snapshot_epoch, &history_meta);
    else
        n = history_snapshot(t, samples, logic::HISTORY_SAMPLES, &history_snapshot_epoch,
                             &history_meta);
    const size_t nruns = (modbus || env3_source)
                             ? 0
                             : logic::history_held_runs(samples, n, runs, logic::HISTORY_MAX_RUNS);

    const char* unit_str = unit;
    if (modbus || env3_source) {
        copy_bounded_str(lbl, sizeof(lbl),
                         modbus ? (mb_reg ? mb_reg->label : "") : ENV3_HISTORIES[env_t].label);
        unit_str = modbus ? (mb_reg ? mb_reg->unit : "") : ENV3_HISTORIES[env_t].unit;
    } else {
        history_label(t, lbl, sizeof(lbl));
        history_unit(t, unit, sizeof(unit));
    }

    std::string j = "{\"id\":\"";
    j += modbus        ? logic::HOMEHUB_HISTORIES[mb_t].trend_id
         : env3_source ? ENV3_HISTORIES[env_t].id
                       : def_->id;
    const bool mqtt_source =
        !modbus && !env3_source && def_->kind == logic::TrendKind::CirculationState;
    j += "\",\"source\":\"";
    j += modbus        ? "modbus"
         : env3_source ? "env3"
         : mqtt_source ? "mqtt"
                       : "x10a";
    // Bind the body to the lifetime captured with its samples, not a successor observed while
    // serializing it. The per-boot token also distinguishes equal epochs on different boots.
    j += "\",\"epoch\":";
    j += std::to_string(history_snapshot_epoch);
    char boot_id[17];
    http_boot_id(boot_id);
    j += ",\"boot_id\":\"";
    j += boot_id;
    j += "\",\"label\":";
    json_append_quoted(j, lbl);
    j += ",\"dt\":";
    static_assert(logic::HISTORY_DT_S == 300);
    // The ROW's unit, never a hardcoded "°C": the trends mix °C, bar and unitless rows, and the
    // browser prints this string straight into the range readout and the crosshair. A bar row
    // labelled °C is exactly the legacy-35–legacy-39 shape.
    j += "300,\"unit\":";
    json_append_quoted(j, unit_str);
    if (n && history_meta.newest_commit_us != logic::HISTORY_NO_COMMIT_US) {
        int64_t unix_s;
        int32_t wall_ms;
        time_now(unix_s, wall_ms);
        int64_t newest;
        if (unix_s >= 0 && logic::history_commit_unix_s(unix_s, wall_ms, esp_timer_get_time(),
                                                        history_meta.newest_commit_us, newest)) {
            const auto oldest = logic::history_t0(newest, n, logic::HISTORY_DT_S);
            if (oldest != INT64_MIN) {
                j += ",\"t0\":";
                append_json_int(j, oldest);
            }
        }
    }
    const int64_t b0 = history_meta.oldest_bucket;
    if (b0 != logic::HISTORY_NO_BUCKET) {
        // Exact source alignment even before SNTP: all recorders derive this monotonic bucket from
        // the same esp_timer clock, so a Modbus line cannot slide onto the neighbouring X10A sample.
        j += b0 < 0 ? ",\"boot_b0\":" : ",\"b0\":";
        append_json_int(j, b0);
    }
    j += ",\"v\":[";
    // Labels and raster metadata use separate bounded getters. If a reset intervened, refuse the
    // assembled header before any chunk is sent rather than mixing predecessor samples with it.
    // Epoch 0 means no snapshot identity at all (no history mutex, or its lock was not obtained);
    // that is reported as unavailable, not as a change a retry would resolve.
    if (history_snapshot_epoch == 0) {
        return send_status_json_err(req, "503 Service Unavailable",
                                    "{\"ok\":false,\"error\":\"history unavailable\"}");
    }
    if (history_snapshot_epoch != history_epoch()) {
        return send_status_json_err(req, "503 Service Unavailable",
                                    "{\"ok\":false,\"error\":\"history changed; retry\"}");
    }
    HttpJsonChunks chunks(HttpChunkEmitter{req});
    httpd_resp_set_type(req, "application/json");
    return finish_bounded_stream(chunks,
                                 [&](auto& out) {
                                     out += j;
                                     for (size_t i = 0; i < n; i++) {
                                         if (i) out += ",";
                                         // Samples are bounded signed tenths. Format without
                                         // allocation after transfer starts.
                                         if (logic::history_is_absent(samples[i]))
                                             out += "null";
                                         else {
                                             const int value = static_cast<int>(samples[i]);
                                             if (value < 0) out += '-';
                                             append_json_uint(
                                                 out, value < 0 ? static_cast<unsigned>(-value)
                                                                : static_cast<unsigned>(value));
                                         }
                                     }
                                     out += "],\"held\":[";
                                     for (size_t i = 0; i < nruns; i++) {
                                         if (i) out += ",";
                                         out += "[";
                                         append_json_uint(out, runs[i][0]);
                                         out += ",";
                                         append_json_uint(out, runs[i][1]);
                                         out += "]";
                                     }
                                     out += "]}";
                                 })
               ? ESP_OK
               : ESP_FAIL;
}

static esp_err_t h_diag(httpd_req_t* req) {
    bool redact = false;
    {
        char q[64];
        if (!read_query(req, q))
            return query_too_long(req); // never downgrade a requested redaction
        // GET is read-only. Destructive clearing is POST /diag/clear, so a link, prefetch or image
        // request can never erase the evidence it was trying to retrieve. ?verbose only changes the
        // setting when present.
        char v[4];
        if (httpd_query_key_value(q, "verbose", v, sizeof(v)) == ESP_OK)
            diag_set_verbose(query_flag_on(v));
        redact = query_flag(q, "redact");
    } // Query scratch has no borrowed consumer during the diagnostic transfer.
    // Plain diagnostics stream from static 1 KiB storage. Redacted per-line strings require
    // their own OTA admission check before the bounded stream starts.
    if (redact && ota_download_active()) return network_tls_busy(req);
    auto(&buf)[1024] = s_httpd_route_scratch.diag_buf;
    static DiagStreamCursor cursor;
    const size_t            max_dump = ota_download_active() ? 512 : kDiagRingBytes;
    cursor                           = diag_stream_open(max_dump);
    httpd_resp_set_type(req, "text/plain");
    if (!redact) {
        // Stream plain /diag in 1 KiB chunks instead of materializing a 6 KiB ring copy. When OTA
        // is actively downloading, max_dump caps the open cursor to 512 B so lwIP queues only a
        // single small TCP pbuf, preventing multi-pbuf internal heap fragmentation while mbedTLS
        // re-allocates its 16 KiB RX record buffer.
        http_set_nodelay(req, false);
        while (const size_t n = diag_stream_next(cursor, buf, sizeof(buf), false)) {
            if (httpd_resp_send_chunk(req, buf, n) != ESP_OK) {
                http_set_nodelay(req, true);
                return ESP_FAIL;
            }
        }
        http_set_nodelay(req, true);
        return httpd_resp_send_chunk(req, nullptr, 0);
    }

    // Redact each record without materializing the ring. A late per-line allocation failure
    // closes the committed stream instead of reaching the outer guard's clean-error response.
    HttpJsonChunks chunks(HttpChunkEmitter{req});
    return finish_bounded_stream(
               chunks,
               [&](auto& out) {
                   while (const size_t n = diag_stream_next(cursor, buf, sizeof(buf), true)) {
                       for (size_t start = 0; start < n;) {
                           size_t eol = start;
                           while (eol < n && buf[eol] != '\n') ++eol;
                           if (eol < n) ++eol;
                           out += redact_diag_line(std::string_view(buf + start, eol - start));
                           start = eol;
                       }
                   }
               })
               ? ESP_OK
               : ESP_FAIL;
}

static esp_err_t h_diag_clear(httpd_req_t* req) {
    diag_clear();
    return http_send_json(req, "{\"ok\":true}");
}

static esp_err_t h_coredump(httpd_req_t* req) {
    // Match /status.last_crash exactly: a raw image proven to belong to another firmware is not a
    // downloadable report. Boot capture preserves its private bytes in the partition and latches
    // suppression. Without this gate the banner says "no dump" while the endpoint serves one that
    // esp-coredump rejects on the ELF SHA mismatch.
    if (!diag_crash_coredump_present()) {
        httpd_resp_set_status(req, "404 Not Found");
        httpd_resp_set_type(req, "text/plain");
        return httpd_resp_sendstr(req, "No reportable coredump found");
    }

    size_t address = 0;
    size_t size = 0;
    esp_err_t err = esp_core_dump_image_get(&address, &size);
    if (err == ESP_ERR_NOT_FOUND) {
        httpd_resp_set_status(req, "404 Not Found");
        httpd_resp_set_type(req, "text/plain");
        return httpd_resp_sendstr(req, "No coredump found");
    } else if (err != ESP_OK) {
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "Failed to retrieve coredump metadata");
    }

    const esp_partition_t* pt = esp_partition_find_first(
        ESP_PARTITION_TYPE_DATA,
        ESP_PARTITION_SUBTYPE_DATA_COREDUMP,
        nullptr
    );
    if (!pt) {
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "Coredump partition not found");
    }

    httpd_resp_set_type(req, "application/octet-stream");
    httpd_resp_set_hdr(req, "Content-Disposition", "attachment; filename=\"coredump.bin\"");

    char chunk[512];
    size_t offset = 0;
    while (offset < size) {
        size_t to_read = (size - offset > sizeof(chunk)) ? sizeof(chunk) : (size - offset);
        if (esp_partition_read(pt, offset, chunk, to_read) != ESP_OK) {
            // Abort chunked transfer by sending end-of-chunks with error status (though HTTP protocol allows just closing connection)
            httpd_resp_send_chunk(req, nullptr, 0);
            return ESP_FAIL;
        }
        if (httpd_resp_send_chunk(req, chunk, to_read) != ESP_OK) {
            return ESP_FAIL;
        }
        offset += to_read;
    }
    // End chunked transfer
    httpd_resp_send_chunk(req, nullptr, 0);
    return ESP_OK;
}

// POST /coredump/clear erases only the raw image and deliberately preserves the reset/crash record.
// That is distinct from /crash/dismiss below, which acknowledges the whole report. Both mutations
// are POSTs so neither can be triggered by a followed link or speculative GET.
static esp_err_t h_coredump_clear(httpd_req_t* req) {
    const esp_err_t err = esp_core_dump_image_erase();
    if (err == ESP_OK) return http_send_json(req, "{\"ok\":true}");
    return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "Failed to erase coredump");
}

// POST /crash/dismiss — acknowledge + DELETE this boot's crash report: erase the core-dump image and
// mark the cached CrashInfo dismissed (diag_crash_dismiss()), so /status.last_crash goes null, the
// retained MQTT crash topic clears on the next heartbeat tick, and the UI banner is gone for good
// rather than for one page view.
//
// Separate from POST /coredump/clear rather than folded into it, because they answer different
// questions: clearing frees the flash slot for the NEXT dump and deliberately leaves the fault reset
// on record, while this says the crash itself has been dealt with. A fault reset carries no dump at
// all in the common case (a stack overflow overruns the dump too), and there /coredump/clear changes
// nothing the banner keys on.
//
// POST, unlike the GET it sits beside: this destroys the one piece of evidence a bug report needs
// (docs/REPORTING.md), so it must not be reachable by a link, a prefetch or a crawler.
static esp_err_t h_crash_dismiss(httpd_req_t* req) {
    if (!diag_crash_dismiss()) {
        return send_status_json_err(req, "500 Internal Server Error",
                                    "{\"ok\":false,\"error\":\"coredump erase failed\"}");
    }
    return http_send_json(req, "{\"ok\":true}");
}

static esp_err_t h_scan(httpd_req_t* req) {
    // A scan materializes arbitrary nearby SSIDs and asks the Wi-Fi stack for a concurrent radio
    // operation. Neither belongs between OTA's admission sample and its TLS/X509 allocations.
    if (ota_download_active()) return network_tls_busy(req);
    WifiScanEntry  e[20];
    int            n = wifi_scan(e, 20);
    HttpJsonChunks chunks(HttpChunkEmitter{req});
    httpd_resp_set_type(req, "application/json");
    return finish_bounded_stream(chunks,
                                 [&e, n](auto& out) {
                                     out += "{\"networks\":[";
                                     for (int i = 0; i < n; i++) {
                                         if (i) out += ',';
                                         out += "{\"ssid\":";
                                         json_append_quoted(out, e[i].ssid);
                                         out += ",\"rssi\":";
                                         const int rssi = e[i].rssi;
                                         if (rssi < 0) out += '-';
                                         append_json_uint(
                                             out, static_cast<unsigned>(rssi < 0 ? -rssi : rssi));
                                         out += '}';
                                     }
                                     out += "]}";
                                 })
               ? ESP_OK
               : ESP_FAIL;
}

void http_register_status(httpd_handle_t s, HttpSurface surface) {
    // Provisioning surface (served on the open setup AP too): the setup page and its inert favicon,
    // nothing else. The portal takes a TYPED SSID, so /scan is NOT part of it
    // (see logic/http_surface.hpp).
    http_register_on(s, surface, "/", HTTP_GET, h_index);
    http_register_on(s, surface, "/index.html", HTTP_GET, h_index);
    http_register_on(s, surface, "/favicon.ico", HTTP_GET, h_favicon);

    // Everything below is trusted-LAN only — withheld from the open setup AP (F01). /diag and
    // /coredump can carry WiFi/MQTT secrets; /status/values/models expose live device state.
    if (!http_surface_serves(surface, "/status", /*is_post=*/false)) return;

    http_register(s, "/heat-pump-icon.png", HTTP_GET, h_heat_pump_icon);
    http_register(s, "/locale.js", HTTP_GET, h_locale);
    http_register(s, "/status", HTTP_GET, h_status);
    http_register(s, "/values", HTTP_GET, h_values);
    http_register(s, "/history", HTTP_GET, h_history);
    http_register(s, "/scan", HTTP_GET, h_scan);

    http_register(s, "/models", HTTP_GET, h_models);
    http_register(s, "/diag", HTTP_GET, h_diag);
    http_register(s, "/diag/clear", HTTP_POST, h_diag_clear);
    http_register(s, "/coredump", HTTP_GET, h_coredump);
    http_register(s, "/coredump/clear", HTTP_POST, h_coredump_clear);
    http_register(s, "/crash/dismiss", HTTP_POST, h_crash_dismiss);
}

// Captive-portal / SPA catch-all — registered LAST (after every specific route) so it only handles
// unmatched GETs: a 302 to the portal in AP mode, the web UI in STA mode (see h_captive). This is
// what makes an OS connectivity probe (routed here by captive_dns.cpp) open the setup portal.
void http_register_captive(httpd_handle_t s) {
    http_register(s, "/*", HTTP_GET, h_captive);
}

