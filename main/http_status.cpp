template <typename JsonOut>
[[gnu::noinline]] static void append_status_tenths_value(JsonOut& j, int value) {
    if (value < 0) j += "-";
    const unsigned magnitude = static_cast<unsigned>(value < 0 ? -value : value);
    append_json_uint(j, magnitude / 10);
    j += ".";
    append_json_uint(j, magnitude % 10);
}

